// Generates apps/web/src/styles/tokens.generated.css (Tailwind 4 @theme) from the
// token source in packages/shared/src/design-tokens/tokens.ts.
// Deterministic: same source, same bytes. CI runs it and then `git diff --exit-code`.
// No dependencies; the source is loaded with Node's type stripping (Node 22.18+).
// Usage: node tools/build-design-tokens.js

const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'packages/shared/src/design-tokens/tokens.ts');
const target = path.join(root, 'apps/web/src/styles/tokens.generated.css');

const rem = (px) => `${px / 16}rem`;
const px = (n) => (n === 0 ? '0' : `${n}px`);
const ms = (n) => `${n}ms`;
const lines = (entries, prefix, value) => entries.map(([name, v]) => `  --${prefix}-${name}: ${value(v)};`);

function render(t) {
  const out = [];
  const block = (title, rows) => out.push('', `  /* ${title} */`, ...rows);

  out.push(
    '/* GENERATED by tools/build-design-tokens.js from packages/shared/src/design-tokens/tokens.ts.',
    '   Do not edit. Spec: docs/design/tokens.md. Dark mode is not defined. */',
    '',
    '@theme {',
    '  --color-*: initial;',
  );
  out.push(...lines(Object.entries(t.colors), 'color', (v) => v));
  block('typography', [
    `  --font-sans: ${t.fontFamily.sans};`,
    ...Object.entries(t.typeStyles).flatMap(([name, s]) => [
      `  --text-${name}: ${rem(s.size)};`,
      `  --text-${name}--line-height: ${rem(s.line)};`,
      `  --text-${name}--font-weight: ${s.weight};`,
    ]),
  ]);
  block('spacing', [
    `  --spacing: ${rem(t.spacingBase)};`,
    ...lines(Object.entries(t.spacingRhythm), 'spacing', (v) => rem(v)),
  ]);
  block('radius', lines(Object.entries(t.radius), 'radius', (v) => px(v)));
  block('shadow', lines(Object.entries(t.shadows), 'shadow', (v) => v));
  block('motion', [
    ...lines(Object.entries(t.motion.duration), 'duration', ms),
    `  --ease-standard: ${t.motion.easing};`,
  ]);
  block('z-index', lines(Object.entries(t.zIndex), 'z', String));
  block('breakpoints', lines(Object.entries(t.breakpoints), 'breakpoint', px));
  out.push('}', '');

  // Tailwind has no theme namespace for duration or z-index: expose them as utilities.
  for (const name of Object.keys(t.motion.duration)) {
    out.push(`@utility duration-${name} {`, `  transition-duration: var(--duration-${name});`, '}', '');
  }
  for (const name of Object.keys(t.zIndex)) {
    out.push(`@utility z-${name} {`, `  z-index: var(--z-${name});`, '}', '');
  }
  return out.join('\n');
}

async function main() {
  const tokens = await import(pathToFileURL(source).href);
  fs.writeFileSync(target, render(tokens));
  console.log(`wrote ${path.relative(root, target)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
